  (value || "").replace(/[^a-z0-9]/gi, "").toUpperCase();

export const isACRoute = (route: string): boolean => {
  const n = normalizeRoute(route);
  return n.startsWith("AC") || n.startsWith("VS") || n.startsWith("V1");
};

export const getRouteStopsCount = (route: WBTCRoute): number => {
  const stops = (route.stops || "").split(/[-–—,;/]/).map((s) => s.trim()).filter(Boolean);
  return Math.max(2, stops.length + 2);
};

export const searchRoutes = (query: string): WBTCRoute[] => {
  if (!query || !query.trim()) return WBTC_ROUTES;
  const q = query.trim().toLowerCase();
  const qNorm = normalizeRoute(q);

  const toMatch = q.match(/^(.+?)\s+(?:to|–|-|->|→)\s+(.+)$/i);
  if (toMatch) {
    const oQuery = toMatch[1].trim();
    const dQuery = toMatch[2].trim();
    return WBTC_ROUTES.filter((r) => {
      const full = `${r.origin} ${r.stops} ${r.destination}`.toLowerCase();
      return full.includes(oQuery) && full.includes(dQuery);
    });
  }

  return WBTC_ROUTES.filter((r) => {
    if (qNorm && normalizeRoute(r.route).includes(qNorm)) return true;
    const text = `${r.route} ${r.origin} ${r.destination} ${r.stops}`.toLowerCase();
    return text.includes(q);
  });
};

export type TripResult = {
  route: WBTCRoute;
  originMatched: string;
  destMatched: string;
  stopsBetween: number;
  isReversed: boolean;
  directionText: string;
};

export const findTripRoutes = (originQuery: string, destQuery: string): TripResult[] => {
  if (!originQuery.trim() || !destQuery.trim()) return [];
  const oq = originQuery.trim().toLowerCase();
  const dq = destQuery.trim().toLowerCase();

  const results: TripResult[] = [];

  WBTC_ROUTES.forEach((route) => {
    const intermediate = (route.stops || "")
      .split(/[-–—,;/]/)
      .map((s) => s.replace(/^via\s*:?\s*/i, "").trim())
      .filter((s) => s.length > 0 && !s.toLowerCase().startsWith("via"));
    const stops = [route.origin.trim(), ...intermediate, route.destination.trim()].filter(Boolean);

    const oIndex = stops.findIndex((s) => s.toLowerCase().includes(oq));
    const dIndex = stops.findIndex((s) => s.toLowerCase().includes(dq));

    if (oIndex !== -1 && dIndex !== -1 && oIndex !== dIndex) {
      if (oIndex < dIndex) {
        results.push({
          route,
          originMatched: stops[oIndex],
          destMatched: stops[dIndex],
          stopsBetween: dIndex - oIndex,
          isReversed: false,
          directionText: `${route.origin} → ${route.destination}`,
        });
      } else {
        results.push({
          route,
          originMatched: stops[oIndex],
          destMatched: stops[dIndex],
          stopsBetween: oIndex - dIndex,
          isReversed: true,
          directionText: `${route.destination} → ${route.origin} (Return)`,
        });
      }
    }
  });

  return results.sort((a, b) => {
    if (a.isReversed !== b.isReversed) return a.isReversed ? 1 : -1;
    return a.stopsBetween - b.stopsBetween;
  });
};

